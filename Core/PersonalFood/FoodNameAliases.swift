        var map: [String: String] = [:]
        for (variant, target) in rawGroups {
            map[MealItemIdentity.canonicalName(variant)] = MealItemIdentity.canonicalName(target)
        }
        return map
    }()

    /// 已是 canonicalName 的键 → 组键；不在表内原样返回。
    static func groupKey(forCanonicalName key: String) -> String {
        canonicalGroups[key] ?? key
    }

    /// 原始食物名 → 组键。
